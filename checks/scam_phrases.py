# Эти категории опасны даже поодиночке
CRITICAL = {"Код из СМС", "Голосование", "Опасный файл", "Официальные лица"}


def check_phrases(text):
    """Ищет маркеры мошенничества в тексте и возвращает сигнал (или None, если ничего не нашли)."""
    low = text.lower()
    found = []  # названия найденных категорий
    reasons = []
    for category, (markers, reason) in PATTERNS.items():
        if any(m in low for m in markers):
            found.append(category)
            reasons.append(f"{category}: {reason}")

    if not found:
        return None

    # Чем больше разных приёмов сразу, тем подозрительнее
    if len(found) >= 2 or CRITICAL & set(found):
        verdict, confidence = "scam", min(0.5 + 0.15 * len(found), 0.9)
    else:
        verdict, confidence = "suspicious", 0.5

    return {
        "name": "💬 Приёмы мошенников",
        "verdict": verdict,
        "confidence": confidence,
        "explanation": "; ".join(reasons),
    }
