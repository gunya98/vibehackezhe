def pick_topic(text):
    """Определяет, о чём сообщение мошенника: берём тему, слова которой встретились чаще всего."""
    low = text.lower()
    best, best_count = DEFAULT, 0
    for words, phrases in TOPICS.values():
        count = sum(w in low for w in words)  # сколько слов темы нашлось в сообщении
        if count > best_count:
            best, best_count = phrases, count
    return best
