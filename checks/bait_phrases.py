# Где в сообщении стоит обращение по имени: «Ольга, …», «Здравствуйте, Ольга!», «Вы Ольга?», «Это Ольга?»
NAME_PATTERNS = [
    r"^\s*([А-ЯЁ][а-яё]{2,})\s*[,!]",
    r"(?i:здравствуйте|добрый день|доброе утро|добрый вечер|привет)\s*,?\s+([А-ЯЁ][а-яё]{2,})",
    r"(?i:\bвы|\bты|\bэто)\s+([А-ЯЁ][а-яё]{2,})\s*\?",
]


def find_called_name(text):
    """Находит имя, которым собеседник назвал владельца («Ольга, здравствуйте!»). Возвращает имя или None."""
    for pattern in NAME_PATTERNS:
        match = re.search(pattern, text)  # (?i:...) в шаблоне — без учёта регистра только для слов-обращений
        if match:
            name = match.group(1)
            if name[0].isupper() and name not in NOT_NAMES:
                return name
    return None


def pick_topic(text):
    """Определяет, о чём сообщение мошенника: берём тему, слова которой встретились чаще всего."""
    low = text.lower()
    best, best_count = DEFAULT, 0
    for words, phrases in TOPICS.values():
        count = sum(w in low for w in words)  # сколько слов темы нашлось в сообщении
        if count > best_count:
            best, best_count = phrases, count
    return best
