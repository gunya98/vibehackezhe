"""Распознаёт грубость собеседника: мат, оскорбления, угрозы.
Нужно, чтобы в режиме приманки вовремя остановиться и передать разговор человеку."""
import re

# Корни слов (без окончаний), чтобы ловить разные формы. Списки можно пополнять.
PATTERNS = {
    "угрозы": [r"убь[юёе]", r"прибь[юёе]", r"найд[уё]м? теб", r"знаю,? где ты жив", r"знаю,? где вы жив",
               r"тебе конец", r"вам конец", r"пожалеешь", r"пожалеете", r"сдохн", r"порежу", r"закопа[юе]",
               r"приед[уе]м? к теб", r"приед[уе]м? к вам"],
    "мат": [r"ху[йеёяию]", r"пизд", r"\bеб(ал|ать|ут|ло|ла|ну|ан(ый|ая|ое|ые|ут))", r"\bъеб", r"заеб", r"уеб", r"выеб", r"\bбля",
            r"мудак", r"мудил", r"гандон", r"залуп"],
    "оскорбления": [r"\bсук[аиу]\b", r"сучк", r"тварь", r"\bурод", r"дебил", r"идиот", r"долбо",
                    r"\bтуп(ой|ая|ое|ые|ица)\b", r"\bлох\b", r"\bлохушк", r"кретин", r"дегенерат", r"чмо",
                    r"\bшлюх", r"\bсоси\b", r"заткни", r"пош[её]л(а|и)?\s+(ты|вы)\b", r"\bиди(те)?\s+(ты|вы)\s+на\b", r"отвали",
                    r"\bбыдло", r"\bскотин"],
}


def check_rudeness(text):
    """Возвращает вид грубости («угрозы», «мат», «оскорбления») или None, если всё прилично.
    Угрозы проверяем первыми: это самое серьёзное."""
    low = text.lower().replace("ё", "е")  # «ё» и «е» считаем одной буквой, поэтому в шаблонах можно писать любую
    for kind, patterns in PATTERNS.items():
        for pattern in patterns:
            if re.search(pattern.replace("ё", "е"), low):
                return kind
    return None
