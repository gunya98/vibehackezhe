def load():
    """Читает профили из файла (или пустой словарь, если файла ещё нет)."""
    try:
        with open(PROFILES_FILE, encoding="utf-8") as f:
            return json.load(f)
    except (FileNotFoundError, json.JSONDecodeError):
        return {}


PROFILES = load()  # id владельца (строкой) -> {"gender": "m"/"f", "age": "young"/...}


def get(owner_id):
    """Профиль владельца; если он ещё не ответил — профиль по умолчанию."""
    return PROFILES.get(str(owner_id), DEFAULT)


def save(owner_id, **fields):
    """Обновляет профиль владельца и сохраняет в файл."""
    profile = dict(get(owner_id))
    profile.update(fields)
    PROFILES[str(owner_id)] = profile
    with open(PROFILES_FILE, "w", encoding="utf-8") as f:
        json.dump(PROFILES, f, ensure_ascii=False, indent=2)


def persona(profile):
    """Описание персонажа для ИИ."""
    return PERSONAS[(profile["gender"], profile["age"])]


def style_examples(profile):
    """Примеры реплик в стиле этого возраста."""
    return STYLE[profile["age"]]


def feminize(text):
    """Переводит готовую фразу в женский род (для заготовок без ИИ)."""
    for male, female in FEMININE.items():
        text = re.sub(rf"\b{male}\b", female, text)
    return text


def gender_buttons():
    """Кнопки «Мужчина / Женщина»."""
    return InlineKeyboardMarkup(inline_keyboard=[[
        InlineKeyboardButton(text="👨 Мужчина", callback_data="prof:g:m"),
        InlineKeyboardButton(text="👩 Женщина", callback_data="prof:g:f"),
    ]])


def age_buttons():
    """Кнопки с возрастом."""
    return InlineKeyboardMarkup(inline_keyboard=[[
        InlineKeyboardButton(text=label, callback_data=f"prof:a:{key}") for key, label in AGES.items()
    ]])


